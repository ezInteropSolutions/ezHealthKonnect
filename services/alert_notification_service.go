// AlertNotificationService dispatches alert notifications to configured channels.
type AlertNotificationService struct {
	db         *sql.DB
	credStore  *CredentialStore // optional; used to decrypt system SMTP settings
	httpClient *http.Client
}

// NewAlertNotificationService creates a new dispatcher.
// An optional CredentialStore may be supplied to enable decryption of the
// system-wide SMTP settings stored in system_settings.
func NewAlertNotificationService(db *sql.DB, credStore ...*CredentialStore) *AlertNotificationService {
	svc := &AlertNotificationService{
		db:         db,
		httpClient: &http.Client{Timeout: 15 * time.Second},
	}
	if len(credStore) > 0 {
		svc.credStore = credStore[0]
	}
	return svc
}

// DispatchToChannel sends a notification to a single channel with 3-attempt retry.
func (n *AlertNotificationService) DispatchToChannel(ctx context.Context, ch *AlertChannel, alert *FiredAlert) error {
	var cfg map[string]interface{}
	if err := json.Unmarshal(ch.Config, &cfg); err != nil {
		return fmt.Errorf("invalid channel config: %w", err)
	}

	// Load system-wide SMTP settings once; used as a fallback inside sendEmail.
	systemSMTP := n.loadSystemSMTP(ctx)

	var lastErr error
	delays := []time.Duration{0, 2 * time.Second, 4 * time.Second}

	for attempt, delay := range delays {
		if delay > 0 {
			select {
			case <-ctx.Done():
				return ctx.Err()
			case <-time.After(delay):
			}
		}

		switch ch.ChannelType {
		case "email":
			lastErr = n.sendEmail(ctx, cfg, systemSMTP, alert)
		case "webhook":
			lastErr = n.sendWebhook(ctx, cfg, alert)
		case "slack":
			lastErr = n.sendSlack(ctx, cfg, alert)
		default:
			return fmt.Errorf("unknown channel type: %s", ch.ChannelType)
		}

		if lastErr == nil {
			return nil
		}
		_ = attempt
	}
	return fmt.Errorf("all dispatch attempts failed: %w", lastErr)
}

// loadSystemSMTP reads and decrypts the system-wide SMTP config from DB.
// Returns nil if unconfigured or DB is unavailable.
func (n *AlertNotificationService) loadSystemSMTP(ctx context.Context) map[string]interface{} {
	if n.db == nil {
		return nil
	}
	var raw string
	err := n.db.QueryRowContext(ctx, `SELECT value FROM system_settings WHERE key = 'smtp'`).Scan(&raw)
	if err != nil {
		return nil
	}
	data := []byte(raw)
	// Decrypt if a credential store is available
	if n.credStore != nil {
		if dec, err := n.credStore.DecryptConfig(json.RawMessage(raw)); err == nil {
			data = dec
		}
	}
	var cfg map[string]interface{}
	_ = json.Unmarshal(data, &cfg)
	// Only return if host is actually configured
	if host, _ := cfg["host"].(string); host == "" {
		return nil
	}
	return cfg
}

