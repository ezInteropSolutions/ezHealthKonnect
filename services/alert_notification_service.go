// sendEmail sends an alert notification email.
// Priority for each SMTP field: per-channel config → system SMTP settings (DB) → env var.
func (n *AlertNotificationService) sendEmail(_ context.Context, cfg map[string]interface{}, systemSMTP map[string]interface{}, alert *FiredAlert) error {
	// Helper to apply three-level fallback
	fallback := func(channelKey, systemKey, envKey string) string {
		if v := getStr(cfg, channelKey, ""); v != "" {
			return v
		}
		if systemSMTP != nil {
			if v := getStr(systemSMTP, systemKey, ""); v != "" {
				return v
			}
		}
		return os.Getenv(envKey)
	}

	smtpHost := fallback("smtp_host", "host", "SMTP_HOST")
	smtpPort := fallback("smtp_port", "port", "SMTP_PORT")
	smtpUser := fallback("smtp_user", "username", "SMTP_USER")
	smtpPass := fallback("smtp_password_enc", "password", "SMTP_PASSWORD")
	fromAddr := fallback("from", "from_address", "SMTP_FROM")
	appBaseURL := os.Getenv("APP_BASE_URL")
	if appBaseURL == "" {
		appBaseURL = "http://localhost:3000"
	}

	if smtpHost == "" {
		return fmt.Errorf("email channel: smtp_host not configured")
	}
	if smtpPort == "" {
		smtpPort = "587"
	}
	if fromAddr == "" {
		fromAddr = "alerts@ezhealthkonnect.local"
	}

	toRaw, _ := cfg["to"]
	var toAddrs []string
	switch v := toRaw.(type) {
	case []interface{}:
		for _, item := range v {
			if s, ok := item.(string); ok {
				toAddrs = append(toAddrs, s)
			}
		}
	case string:
		toAddrs = []string{v}
	}
	if len(toAddrs) == 0 {
		return fmt.Errorf("email channel: no recipients configured")
	}

	severityColor := "#f59e0b" // warning amber
	severityLabel := "WARNING"
	if alert.Severity == "critical" {
		severityColor = "#dc2626"
		severityLabel = "CRITICAL"
	} else if alert.Severity == "info" {
		severityColor = "#db2777"
		severityLabel = "INFO"
	}

	var htmlBuf bytes.Buffer
	_ = emailHTMLTemplate.Execute(&htmlBuf, emailTemplateData{
		SeverityColor: severityColor,
		SeverityLabel: severityLabel,
		AlertType:     alert.AlertType,
		InterfaceName: alert.InterfaceName,
		Severity:      strings.ToUpper(alert.Severity),
		Message:       alert.Message,
		CreatedAt:     alert.CreatedAt,
		AlertsURL:     appBaseURL + "/alerts.html",
	})

	subject := fmt.Sprintf("[%s] %s — %s", strings.ToUpper(alert.Severity), alert.AlertType, alert.InterfaceName)
	body := fmt.Sprintf(
		"To: %s\r\nFrom: %s\r\nSubject: %s\r\nMIME-Version: 1.0\r\nContent-Type: text/html; charset=UTF-8\r\n\r\n%s",
		strings.Join(toAddrs, ", "), fromAddr, subject, htmlBuf.String(),
	)

	addr := net.JoinHostPort(smtpHost, smtpPort)

	var auth smtp.Auth
	if smtpUser != "" {
		auth = smtp.PlainAuth("", smtpUser, smtpPass, smtpHost)
	}

	// STARTTLS
	tlsCfg := &tls.Config{ServerName: smtpHost, MinVersion: tls.VersionTLS12}
	conn, err := tls.Dial("tcp", addr, tlsCfg)
	if err != nil {
		// Fall back to plain SMTP with STARTTLS upgrade
		return smtp.SendMail(addr, auth, fromAddr, toAddrs, []byte(body))
	}
	defer conn.Close()

	client, err := smtp.NewClient(conn, smtpHost)
	if err != nil {
		return err
	}
	defer client.Quit()

	if auth != nil {
		if err := client.Auth(auth); err != nil {
			return err
		}
	}
	if err := client.Mail(fromAddr); err != nil {
		return err
	}
	for _, rcpt := range toAddrs {
		if err := client.Rcpt(rcpt); err != nil {
			return err
		}
	}
	wc, err := client.Data()
	if err != nil {
		return err
	}
	if _, err := io.WriteString(wc, body); err != nil {
		return err
	}
	return wc.Close()
}

// ─── Generic Webhook ───────────────────────────────────────────────────────────

// webhookPayload is the standard JSON body sent to all webhook/Slack channels.
type webhookPayload struct {
	Source        string                 `json:"source"`
	AlertType     string                 `json:"alert_type"`
	Severity      string                 `json:"severity"`
	Message       string                 `json:"message"`
	InterfaceID   *string                `json:"interface_id"`
	InterfaceName string                 `json:"interface_name"`
	FiredAt       string                 `json:"fired_at"`
	Context       map[string]interface{} `json:"context,omitempty"`
}

func buildWebhookPayload(alert *FiredAlert) webhookPayload {
	return webhookPayload{
		Source:        "ezHealthKonnect",
		AlertType:     alert.AlertType,
		Severity:      alert.Severity,
		Message:       alert.Message,
		InterfaceID:   alert.InterfaceID,
		InterfaceName: alert.InterfaceName,
		FiredAt:       alert.CreatedAt,
	}
}

func (n *AlertNotificationService) sendWebhook(ctx context.Context, cfg map[string]interface{}, alert *FiredAlert) error {
	url := getStr(cfg, "url", "")
	if url == "" {
		return fmt.Errorf("webhook channel: url not configured")
	}
	method := strings.ToUpper(getStr(cfg, "method", "POST"))
	timeoutSecs := int(getFloat(cfg, "timeout_seconds", 10))

	payload, _ := json.Marshal(buildWebhookPayload(alert))

	req, err := http.NewRequestWithContext(ctx, method, url, bytes.NewReader(payload))
	if err != nil {
		return err
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("User-Agent", "ezHealthKonnect-AlertManager/1.0")

	// Custom headers (e.g. Authorization)
	if headers, ok := cfg["headers"].(map[string]interface{}); ok {
		for k, v := range headers {
			if sv, ok := v.(string); ok {
				req.Header.Set(k, sv)
			}
		}
	}

	client := &http.Client{Timeout: time.Duration(timeoutSecs) * time.Second}
	resp, err := client.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode >= 400 {
		return fmt.Errorf("webhook returned HTTP %d", resp.StatusCode)
	}
	return nil
}

// ─── Slack ─────────────────────────────────────────────────────────────────────

func (n *AlertNotificationService) sendSlack(ctx context.Context, cfg map[string]interface{}, alert *FiredAlert) error {
	webhookURL := getStr(cfg, "webhook_url", "")
	if webhookURL == "" {
		return fmt.Errorf("slack channel: webhook_url not configured")
	}
	channel := getStr(cfg, "channel", "#alerts")
	username := getStr(cfg, "username", "ezHealthKonnect")
	iconEmoji := getStr(cfg, "icon_emoji", ":hospital:")

	color := "#f59e0b"
	if alert.Severity == "critical" {
		color = "#dc2626"
	} else if alert.Severity == "info" {
		color = "#db2777"
	}

	title := fmt.Sprintf("[%s] %s", strings.ToUpper(alert.Severity), alert.AlertType)

	slackBody := map[string]interface{}{
		"channel":    channel,
		"username":   username,
		"icon_emoji": iconEmoji,
		"text":       title,
		"attachments": []map[string]interface{}{
			{
				"color": color,
				"fields": []map[string]interface{}{
					{"title": "Message", "value": alert.Message, "short": false},
					{"title": "Interface", "value": alert.InterfaceName, "short": true},
					{"title": "Severity", "value": strings.ToUpper(alert.Severity), "short": true},
					{"title": "Fired At", "value": alert.CreatedAt, "short": true},
				},
				"footer": "ezHealthKonnect Alert Management",
			},
		},
	}

	body, _ := json.Marshal(slackBody)
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, webhookURL, bytes.NewReader(body))
	if err != nil {
		return err
	}
	req.Header.Set("Content-Type", "application/json")

	resp, err := n.httpClient.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode >= 400 {
		return fmt.Errorf("slack webhook returned HTTP %d", resp.StatusCode)
	}
	return nil
}

// ─── Helpers ───────────────────────────────────────────────────────────────────

func getStr(m map[string]interface{}, key, fallback string) string {
	if v, ok := m[key]; ok {
		if s, ok := v.(string); ok && s != "" {
			return s
		}
	}
	return fallback
}

func getFloat(m map[string]interface{}, key string, fallback float64) float64 {
	if v, ok := m[key]; ok {
		switch n := v.(type) {
		case float64:
			return n
		case int:
			return float64(n)
		}
	}
	return fallback
}
