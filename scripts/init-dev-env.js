#!/usr/bin/env node
// scripts/init-dev-env.js — create or complete the local .env.
//
// Creates .env from .env.example with freshly generated secrets, or — when
// .env already exists — appends only the secrets it is missing. Never
// overwrites an existing value and never prints a secret. Used by
// `npm run setup:env` and by CI, which generates throwaway values per run.
//
// Usage: node scripts/init-dev-env.js [--env <path>] [--example <path>]
'use strict';

const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

/**
 * Generators per secret. URL-safe alphabets so values can sit inside a
 * connection string without escaping.
 */
const SECRET_GENERATORS = {
    SESSION_SECRET: () => crypto.randomBytes(48).toString('base64url'),
    JWT_SECRET: () => crypto.randomBytes(48).toString('base64url'),
    APP_CREDENTIAL_KEY: () => crypto.randomBytes(32).toString('base64'),
    DB_PASSWORD: () => crypto.randomBytes(18).toString('hex'),
    MINIO_PASSWORD: () => crypto.randomBytes(18).toString('hex'),
};

function parseEnv(text) {
    const values = {};
    for (const line of text.split(/\r?\n/)) {
        const m = line.match(/^\s*([A-Z0-9_]+)\s*=(.*)$/);
        if (m) values[m[1]] = m[2].trim();
    }
    return values;
}

/**
 * Returns the new .env text and the names of secrets that were generated.
 * @param {string|null} existing  current .env text, or null when absent
 * @param {string} example        .env.example text
 */
function buildEnv(existing, example, generators = SECRET_GENERATORS) {
    const generated = [];
    if (existing === null) {
        const text = example.split(/\r?\n/).map((line) => {
            const m = line.match(/^([A-Z0-9_]+)=\s*$/);
            if (m && generators[m[1]]) {
                generated.push(m[1]);
                return `${m[1]}=${generators[m[1]]()}`;
            }
            return line;
        }).join('\n');
        return { text, generated };
    }

    const current = parseEnv(existing);
    const additions = [];
    for (const [name, gen] of Object.entries(generators)) {
        if (!current[name]) {
            generated.push(name);
            additions.push(`${name}=${gen()}`);
        }
    }
    if (additions.length === 0) return { text: existing, generated };
    const sep = existing.endsWith('\n') ? '' : '\n';
    return { text: `${existing}${sep}\n# Generated by scripts/init-dev-env.js\n${additions.join('\n')}\n`, generated };
}

function main(argv) {
    const arg = (flag, fallback) => {
        const i = argv.indexOf(flag);
        return i >= 0 ? argv[i + 1] : fallback;
    };
    const root = path.join(__dirname, '..');
    const envPath = arg('--env', path.join(root, '.env'));
    const examplePath = arg('--example', path.join(root, '.env.example'));

    const example = fs.readFileSync(examplePath, 'utf8');
    const existing = fs.existsSync(envPath) ? fs.readFileSync(envPath, 'utf8') : null;
    const { text, generated } = buildEnv(existing, example);
    if (text !== existing) fs.writeFileSync(envPath, text, { mode: 0o600 });

    if (existing === null) console.log(`Created ${envPath} with generated secrets: ${generated.join(', ')}`);
    else if (generated.length) console.log(`Added missing secrets to ${envPath}: ${generated.join(', ')}`);
    else console.log(`${envPath} already has every required secret — nothing changed`);
}

if (require.main === module) main(process.argv.slice(2));

module.exports = { buildEnv, parseEnv, SECRET_GENERATORS };
