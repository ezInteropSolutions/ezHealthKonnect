// Helper method: Convert transformation engine MappingRule to wizard view
func (ctrl *WizardController) toWizardView(rule fhir.MappingRule) WizardMappingRuleView {
	// Extract transformation type from TransformLogic
	transformType := "direct" // default
	if rule.TransformLogic != nil {
		if typeVal, ok := rule.TransformLogic["type"].(string); ok {
			transformType = typeVal
		}
	}

	// Get human-readable name for HL7 field
	hl7Name := ctrl.getHL7FieldName(rule.HL7Segment, rule.HL7Field)

	// Convert TransformLogic to TransformationConfig for wizard
	transformConfig := make(map[string]interface{})
	if rule.TransformLogic != nil {
		transformConfig = rule.TransformLogic
	}

	return WizardMappingRuleView{
		ID:                   rule.ID,
		HL7Segment:           rule.HL7Segment,
		HL7Field:             rule.HL7Field,
		HL7Name:              hl7Name,
		FHIRResource:         rule.FHIRResource,
		FHIRPath:             rule.FHIRPath,
		TransformationType:   transformType,
		TransformationConfig: transformConfig,
		Confidence:           "high", // Default confidence
		Enabled:              true,   // Default enabled
		AutoGenerated:        true,   // Default auto-generated
		Mapped:               true,   // Default mapped
	}
}

// Helper method: Convert wizard view back to transformation engine MappingRule
func (ctrl *WizardController) fromWizardView(view WizardMappingRuleView) fhir.MappingRule {
	// Use TransformationConfig if available, otherwise create from TransformationType
	transformLogic := view.TransformationConfig
	if transformLogic == nil {
		transformLogic = map[string]interface{}{
			"type": view.TransformationType,
		}
	}

	return fhir.MappingRule{
		ID:             view.ID,
		HL7Segment:     view.HL7Segment,
		HL7Field:       view.HL7Field,
		FHIRResource:   view.FHIRResource,
		FHIRPath:       view.FHIRPath,
		TransformLogic: transformLogic,
		Priority:       view.ID, // Use ID as priority for now
		Required:       false,   // Default
	}
}

