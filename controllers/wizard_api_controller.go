// ParseHL7 handles HL7 message parsing for the wizard
func (ctrl *WizardController) ParseHL7(c *gin.Context) {
	var req WizardParseRequest
	if err := c.ShouldBindJSON(&req); err != nil {
		c.JSON(http.StatusBadRequest, WizardParseResponse{
			Error: fmt.Sprintf("Invalid request: %v", err),
		})
		return
	}

	if ctrl.config.VerboseLogging {
		fmt.Printf("🎯 Wizard HL7 Parse: %s (length: %d)\n", req.MessageType, len(req.Content))
	}

	// Use your existing HL7 parser
	result := hl7.ParseHL7Enhanced(req.Content)
	if result == nil {
		c.JSON(http.StatusInternalServerError, WizardParseResponse{
			Error: "Parser returned null result",
		})
		return
	}

	if !result.Success {
		c.JSON(http.StatusBadRequest, WizardParseResponse{
			Error: result.Error,
		})
		return
	}

	// Convert to wizard format - FIXED to match your HL7 types
	segments := make(map[string]interface{})
	zSegments := make(map[string]interface{})

	for segName, segment := range result.EnhancedSegments {
		segmentData := make(map[string]string)

		// FIXED: Simple iteration over Fields
		for i := 0; i < len(segment.Fields); i++ {
			fieldKey := strconv.Itoa(i + 1) // HL7 fields typically start at 1
			segmentData[fieldKey] = segment.Fields[i].Value
		}

		if strings.HasPrefix(segName, "Z") {
			zSegments[segName] = segmentData
		} else {
			segments[segName] = segmentData
		}
	}

	// Extract metadata - FIXED and simplified
	sendingApp := ""
	messageVersion := "2.5" // Default version

	// Try to extract sending application from MSH segment
	if mshSegment, exists := result.EnhancedSegments["MSH"]; exists && len(mshSegment.Fields) > 3 {
		sendingApp = mshSegment.Fields[3].Value
	}

	response := WizardParseResponse{
		Data: &WizardParsedData{
			Segments:         segments,
			ZSegments:        zSegments,
			EnhancedSegments: segments, // Same as segments for now
			RawMessage:       req.Content,
		},
		Metadata: &WizardMetadata{
			MessageType:        result.MessageType.Name,
			Version:            messageVersion, // FIXED: Use default since Version field doesn't exist
			TotalSegments:      len(result.EnhancedSegments),
			TotalFields:        ctrl.countTotalFields(result.EnhancedSegments), // FIXED: Pass correct type
			Timestamp:          time.Now().Format(time.RFC3339),
			SendingApplication: sendingApp,
			Warnings:           []string{},
			Errors:             []string{},
		},
	}

	c.JSON(http.StatusOK, response)
}

