func (c *SchemaFHIRTransformController) BatchUpdateRules(ctx *gin.Context) {
	var request struct {
		MessageType string        `json:"messageType" binding:"required"`
		Profile     string        `json:"profile"`
		Rules       []MappingRule `json:"rules" binding:"required"`
		AutoFix     bool          `json:"autoFix"`
	}

	if err := ctx.ShouldBindJSON(&request); err != nil {
		ctx.JSON(http.StatusBadRequest, gin.H{
			"success": false,
			"error":   "Invalid request format",
			"details": err.Error(),
		})
		return
	}

	if request.Profile == "" {
		request.Profile = "base"
	}

	// Validate rules against schemas
	validationResults := c.validateRulesAgainstSchemas(request.Rules, request.MessageType, request.Profile)

	if request.AutoFix {
		// Auto-fix common issues
		request.Rules = c.autoFixMappingIssues(request.Rules, validationResults)
		validationResults = c.validateRulesAgainstSchemas(request.Rules, request.MessageType, request.Profile)
	}

	// Save to database
	savedCount, err := c.saveRulesToDB(request.MessageType, request.Profile, request.Rules)
	if err != nil {
		ctx.JSON(http.StatusInternalServerError, gin.H{
			"success": false,
			"error":   "Failed to save mapping rules",
			"details": err.Error(),
		})
		return
	}

	ctx.JSON(http.StatusOK, gin.H{
		"success":           true,
		"saved":             savedCount,
		"validationResults": validationResults,
		"autoFixed":         request.AutoFix,
		"timestamp":         time.Now().Format(time.RFC3339),
	})
}

