type MappingRule struct {
	ID             int                    `json:"id"`
	HL7MessageType string                 `json:"hl7MessageType"`
	HL7Segment     string                 `json:"hl7Segment"`
	HL7Field       string                 `json:"hl7Field"`
	HL7Component   *string                `json:"hl7Component,omitempty"`
	FHIRResource   string                 `json:"fhirResource"`
	FHIRProfile    string                 `json:"fhirProfile"`
	FHIRPath       string                 `json:"fhirPath"`
	TransformLogic map[string]interface{} `json:"transformLogic"`
	ConditionExpr  *string                `json:"conditionExpr,omitempty"`
	Confidence     string                 `json:"confidence"` // high, medium, low
	Priority       int                    `json:"priority"`
	Required       bool                   `json:"required"`
	Enabled        bool                   `json:"enabled"`
	AutoGenerated  bool                   `json:"autoGenerated"`
	CreatedAt      time.Time              `json:"createdAt"`
	UpdatedAt      time.Time              `json:"updatedAt"`
}

type HL7FieldStructure struct {
	Segment     string               `json:"segment"`
	Fields      []HL7FieldDefinition `json:"fields"`
	Description string               `json:"description"`
}

type HL7FieldDefinition struct {
	Field       string                   `json:"field"`
	Name        string                   `json:"name"`
	Description string                   `json:"description"`
	DataType    string                   `json:"dataType"`
	Required    bool                     `json:"required"`
	Repeatable  bool                     `json:"repeatable"`
	Components  []HL7ComponentDefinition `json:"components,omitempty"`
}

type HL7ComponentDefinition struct {
	Component string `json:"component"`
	Name      string `json:"name"`
	DataType  string `json:"dataType"`
	Required  bool   `json:"required"`
}

type FHIRResourceStructure struct {
	ResourceType string                `json:"resourceType"`
	Profile      string                `json:"profile"`
	Fields       []FHIRFieldDefinition `json:"fields"`
	Required     []string              `json:"required"`
	MustSupport  []string              `json:"mustSupport"`
}

type FHIRFieldDefinition struct {
	Path        string  `json:"path"`
	Name        string  `json:"name"`
	Type        string  `json:"type"`
	Description string  `json:"description"`
	Required    bool    `json:"required"`
	MustSupport bool    `json:"mustSupport"`
	Cardinality string  `json:"cardinality"`
	ValueSet    *string `json:"valueSet,omitempty"`
}

