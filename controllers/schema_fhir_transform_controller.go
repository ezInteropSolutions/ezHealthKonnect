func (c *SchemaFHIRTransformController) GetRules(ctx *gin.Context) {
	messageType := ctx.Query("messageType")
	profile := ctx.DefaultQuery("profile", "base")
	includeMetadata := ctx.DefaultQuery("includeMetadata", "false") == "true"

	if messageType == "" {
		ctx.JSON(http.StatusBadRequest, gin.H{
			"success": false,
			"error":   "messageType parameter is required",
			"example": "?messageType=ADT^A01&profile=base&includeMetadata=true",
		})
		return
	}

	// Load existing rules from database
	rules, err := c.loadMappingRulesFromDB(messageType, profile)
	if err != nil {
		ctx.JSON(http.StatusInternalServerError, gin.H{
			"success": false,
			"error":   "Failed to load mapping rules",
			"details": err.Error(),
		})
		return
	}

	response := gin.H{
		"success":     true,
		"messageType": messageType,
		"profile":     profile,
		"rules":       rules,
		"count":       len(rules),
	}

	if includeMetadata {
		// Add UI-specific metadata
		hl7Structure, _ := c.getHL7StructureForMessageType(messageType)
		fhirStructure, _ := c.getFHIRStructureForProfile(profile)

		response["sourceStructure"] = hl7Structure
		response["targetStructure"] = fhirStructure
		response["mappingStats"] = c.getMappingStatistics(rules)
		response["validationIssues"] = c.validateMappingCompleteness(rules, hl7Structure, fhirStructure)
	}

	ctx.JSON(http.StatusOK, response)
}

