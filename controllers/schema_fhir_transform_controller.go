func (c *SchemaFHIRTransformController) getMappingStatistics(rules []MappingRule) map[string]interface{} {
	stats := map[string]interface{}{
		"total": len(rules),
		"byConfidence": map[string]int{
			"high":   0,
			"medium": 0,
			"low":    0,
		},
		"byStatus": map[string]int{
			"mapped":   0,
			"unmapped": 0,
			"errors":   0,
		},
	}

	for _, rule := range rules {
		if conf, ok := stats["byConfidence"].(map[string]int); ok {
			conf[rule.Confidence]++
		}
		if rule.Enabled {
			if status, ok := stats["byStatus"].(map[string]int); ok {
				status["mapped"]++
			}
		}
	}

	return stats
}

func (c *SchemaFHIRTransformController) validateMappingCompleteness(rules []MappingRule, hl7Structure map[string]HL7FieldStructure, fhirStructure map[string]FHIRResourceStructure) []map[string]interface{} {
	var issues []map[string]interface{}

	// Check for unmapped required FHIR fields
	for resourceType, resource := range fhirStructure {
		for _, field := range resource.Fields {
			if field.Required || field.MustSupport {
				mapped := false
				for _, rule := range rules {
					if rule.FHIRResource == resourceType && rule.FHIRPath == field.Path && rule.Enabled {
						mapped = true
						break
					}
				}
				if !mapped {
					issues = append(issues, map[string]interface{}{
						"type":        "unmapped_required",
						"severity":    "error",
						"resource":    resourceType,
						"field":       field.Path,
						"description": fmt.Sprintf("%s.%s is required but not mapped", resourceType, field.Path),
					})
				}
			}
		}
	}

	return issues
}

